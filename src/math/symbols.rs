/// Namnet för ett funktionsnamn om texten är ett känt (för OMML → LaTeX).
pub fn function_limits(name: &str) -> Option<bool> {
    FUNCTIONS.iter().find(|(n, _)| *n == name).map(|(_, l)| *l)
}

pub fn symbol(name: &str) -> Option<(char, Class)> {
    SYMBOLS.iter().find(|(n, _, _)| *n == name).map(|(_, c, k)| (*c, *k))
}

/// Kommandonamn för ett tecken (första träffen), för LaTeX-utskrift.
pub fn command_for(ch: char) -> Option<&'static str> {
    SYMBOLS.iter().find(|(n, c, _)| *c == ch && n.chars().all(|x| x.is_ascii_alphabetic())).map(|(n, _, _)| *n)
}

/// Klass för ett lösryckt Unicode-tecken.
pub fn class_of_char(ch: char) -> Class {
    if let Some((_, _, k)) = SYMBOLS.iter().find(|(_, c, _)| *c == ch) {
        return *k;
    }
    match ch {
        '+' | '\u{2212}' | '*' | '\u{2217}' => Bin,
        '=' | '<' | '>' | ':' => Rel,
        '(' | '[' => Open,
        ')' | ']' => Close,
        ',' | ';' => Punct,
        _ => Ord,
    }
}
